const fs = require('fs'); const { Client } = require('pg');
const APP = require('path').resolve(__dirname, '../../supabase');
let pass = 0, fail = 0; const ok = (c, m) => { c ? pass++ : fail++; console.log(c ? '  ok   ' : '  FALHA', m); };
(async () => {
  const a = new Client({ host: '127.0.0.1', port: 54999, user: 'postgres', database: 'postgres' }); await a.connect();
  await a.query('drop database if exists e'); await a.query('create database e'); await a.end();
  const db = new Client({ host: '127.0.0.1', port: 54999, user: 'postgres', database: 'e' }); await db.connect();
  const run = (f) => db.query(fs.readFileSync(f, 'utf8').replace(/create extension if not exists pg_net;/, ''));
  await run(__dirname + '/bootstrap.sql');
  for (const m of fs.readdirSync(`${APP}/migrations`).sort()) await run(`${APP}/migrations/${m}`);
  await run(`${APP}/seed.sql`);

  const as = async (uid, sql, params = [], aal = 'aal1') => {
    await db.query('begin');
    try {
      await db.query(`set local role ${uid ? 'authenticated' : 'anon'}`);
      await db.query(`select set_config('request.jwt.claim.sub', $1, true), set_config('request.jwt.claims', $2, true)`, [uid ?? '', JSON.stringify({ sub: uid, aal })]);
      const r = await db.query(sql, params); await db.query('commit'); return r;
    } catch (e) { await db.query('rollback'); return { error: e.message, rows: [], rowCount: 0 }; }
  };
  const one = async (uid, sql, params) => { const r = await as(uid, sql, params); if (r.error) throw new Error(r.error); return r.rows[0]; };
  const signup = async (name, role = 'cliente') => (await db.query('insert into auth.users (raw_user_meta_data) values ($1) returning id', [{ full_name: name, role }])).rows[0].id;
  const pro = await signup('Marcos Pereira', 'profissional');
  await as(pro, "insert into public.professional_services values ($1, 'encanador')", [pro]);
  await as(pro, "select public.register_push_token('ExponentPushToken[pro]', 'ios')");
  const admin = await signup('Equipe Resolve');
  await db.query('insert into private.admins (user_id) values ($1)', [admin]);
  const adm = (sql, params = []) => as(admin, sql, params, 'aal2');

  // Serviço combinado começando daqui a `hours` horas.
  const deal = async (cli, hours = -1) => {
    const conv = (await one(cli, 'select id from public.open_conversation($1)', [pro])).id;
    const req = (await one(cli, "select request_id from public.create_request($1, 'encanador', 'Torneira', 'Hoje')", [conv])).request_id;
    const prop = (await one(pro, "insert into public.proposals (conversation_id, request_id, amount, scheduled_label, scheduled_at) values ($1, $2, 150, 'x', now() + interval '2 hours') returning id", [conv, req])).id;
    const order = await one(cli, 'select * from public.accept_proposal($1)', [prop]);
    await db.query('update public.orders set scheduled_at = now() + make_interval(hours => $2) where id = $1', [order.id, hours]);
    return { order: order.id, conv };
  };
  const get = async (id) => (await db.query('select * from public.orders where id = $1', [id])).rows[0];
  const jobs = async () => (await db.query('select jobs_count from public.professionals where id = $1', [pro])).rows[0].jobs_count;
  const lastNote = async (conv) => (await db.query("select body from public.messages where conversation_id = $1 and kind = 'system' order by created_at desc, id desc limit 1", [conv])).rows[0]?.body;
  const done = (id, photos = []) => as(pro, 'select * from public.mark_order_done($1, $2)', [id, photos]);
  const confirm = (uid, id, yes) => as(uid, 'select * from public.confirm_order_done($1, $2)', [id, yes]);
  const age = (id, interval) => db.query(`update public.orders set done_at = now() - interval '${interval}' where id = $1`, [id]);
  const followups = async () => (await db.query('select private.service_followups() n')).rows[0].n;

  console.log('\nServiço feito');
  const ana = await signup('Ana Souza');
  const s1 = await deal(ana, 5);
  ok((await done(s1.order)).error?.includes('a partir do dia e período combinados'), 'antes do começo do período: não dá para marcar feito');
  await db.query("update public.orders set scheduled_at = now() - interval '1 hour' where id = $1", [s1.order]);
  ok((await as(ana, 'select public.mark_order_done($1)', [s1.order])).error?.includes('Só o profissional'), 'cliente não marca feito');
  ok((await as(ana, 'select public.complete_order($1)', [s1.order])).error?.includes('ainda não marcou'), 'cliente não conclui sozinho (nem pelo botão antigo)');
  ok((await done(s1.order, ['outro-servico/foto.jpg'])).error?.includes('Foto inválida'), 'foto de outra pasta: recusada');
  ok((await done(s1.order, [1, 2, 3, 4].map((n) => `${s1.order}/${n}.jpg`))).error?.includes('no máximo 3'), 'mais de 3 fotos: recusado');
  ok(!(await done(s1.order)).error, 'profissional marca feito no período combinado');
  ok((await get(s1.order)).status === 'combinado' && !!(await get(s1.order)).done_at, 'continua combinado, aguardando o cliente');
  ok((await lastNote(s1.conv)) === 'Serviço marcado como feito. Ana, confirme se foi feito.', 'aviso no chat');
  ok((await done(s1.order)).error?.includes('já marcou'), 'não marca duas vezes');
  ok((await as(ana, 'select public.cancel_order($1)', [s1.order])).error?.includes('Responda primeiro'), 'aguardando: cliente não cancela');
  ok((await as(pro, "select public.cancel_order($1, 'x')", [s1.order])).error?.includes('Aguarde o cliente'), 'aguardando: profissional não cancela');
  ok((await as(pro, "select public.request_reschedule($1, now() + interval '1 day', 'Amanhã')", [s1.order])).error?.includes('esperando o cliente'), 'aguardando: ninguém remarca');
  ok((await confirm(pro, s1.order, true)).error?.includes('Só o cliente'), 'profissional não confirma o próprio serviço');
  const before = await jobs();
  ok(!(await confirm(ana, s1.order, true)).error, 'cliente confirma');
  const c1 = await get(s1.order);
  ok(c1.status === 'concluido' && c1.completed_by === 'cliente' && (await jobs()) === before + 1, 'concluído pelo cliente, conta para o profissional');
  ok(!(await as(ana, 'select public.rate_order($1, 5)', [s1.order])).error, 'avaliação liberada');

  console.log('\nNão foi feito, remarcar');
  const s2 = await deal(ana);
  await done(s2.order);
  ok(!(await confirm(ana, s2.order, false)).error, 'cliente diz que não foi feito');
  const c2 = await get(s2.order);
  ok(c2.status === 'combinado' && !c2.done_at && c2.done_blocked && !!c2.done_contested_at, 'volta a combinado, bloqueado para "feito"');
  ok((await lastNote(s2.conv)) === 'Ana disse que o serviço não foi feito. Remarquem ou cancelem.', 'aviso no chat');
  ok((await done(s2.order)).error?.includes('Remarquem antes'), 'profissional não marca feito de novo sem remarcar');
  ok((await as(pro, "select public.request_reschedule($1, now() - interval '6 hours', 'Ontem')", [s2.order])).error?.includes('ainda não passaram'), 'remarcar para o passado: recusado');
  ok((await as(pro, "select public.request_reschedule($1, now() + interval '91 days', 'Longe')", [s2.order])).error?.includes('90 dias'), 'remarcar para mais de 90 dias: recusado');
  ok(!(await as(pro, "select public.request_reschedule($1, now() + interval '1 day', 'Sex 17/10, tarde')", [s2.order])).error, 'profissional propõe nova data');
  ok((await lastNote(s2.conv)) === 'Marcos propôs remarcar para Sex 17/10, tarde.', 'aviso no chat');
  ok((await as(pro, 'select public.respond_reschedule($1, true)', [s2.order])).error?.includes('Espere a outra pessoa'), 'quem pediu não aceita o próprio pedido');
  ok(!(await as(ana, 'select public.respond_reschedule($1, true)', [s2.order])).error, 'cliente aceita');
  const c3 = await get(s2.order);
  ok(c3.scheduled_label === 'Sex 17/10, tarde' && !c3.done_blocked && !c3.reschedule_at && !c3.reminded_at, 'nova data valendo, desbloqueado, lembrete do dia rearmado');
  ok((await lastNote(s2.conv)) === 'Remarcado para Sex 17/10, tarde.', 'aviso no chat');
  await as(ana, "select public.request_reschedule($1, now() + interval '2 days', 'Sáb 18/10, manhã')", [s2.order]);
  ok(!(await as(ana, 'select public.respond_reschedule($1, false)', [s2.order])).error && (await lastNote(s2.conv)) === 'Ana desistiu de remarcar para Sáb 18/10, manhã.', 'quem pediu pode desistir');
  await as(pro, "select public.request_reschedule($1, now() + interval '2 days', 'Sáb 18/10, manhã')", [s2.order]);
  ok(!(await as(ana, 'select public.respond_reschedule($1, false)', [s2.order])).error && (await lastNote(s2.conv)) === 'Ana não aceitou remarcar para Sáb 18/10, manhã.', 'o outro pode recusar');
  await as(pro, "select public.request_reschedule($1, now() + interval '1 day', 'Amanhã')", [s2.order]);
  await db.query("update public.orders set reschedule_at = now() - interval '5 hours' where id = $1", [s2.order]);
  await followups();
  ok(!(await get(s2.order)).reschedule_at && (await lastNote(s2.conv)) === 'O pedido de remarcação venceu: a data passou sem resposta.', 'remarcação cuja data passou vence');

  console.log('\nCancelar');
  const bia = await signup('Bia Lima');
  const s4 = await deal(bia, -30);
  ok((await as(pro, 'select public.cancel_order($1)', [s4.order])).error?.includes('Conte o motivo'), 'profissional depois do dia, sem ter feito: pede motivo');
  ok((await one(pro, "select canceled_late from public.cancel_order($1, 'Não consegui ir')", [s4.order])).canceled_late === true, '…e conta como em cima da hora');
  const s5 = await deal(bia, -30);
  ok((await one(bia, 'select canceled_late from public.cancel_order($1)', [s5.order])).canceled_late === false, 'cliente depois do dia: livre');
  const s6 = await deal(bia, 2);
  await db.query("update public.orders set done_contested_at = now(), done_blocked = true where id = $1", [s6.order]);
  ok((await one(bia, 'select canceled_late from public.cancel_order($1)', [s6.order])).canceled_late === false, 'cliente depois de "não foi feito": livre mesmo em cima da hora');
  const s7 = await deal(bia, 2);
  ok((await as(bia, 'select public.cancel_order($1)', [s7.order])).error?.includes('Conte o motivo'), 'cliente em cima da hora (regra de antes): pede motivo');

  console.log('\nCliente que não responde');
  const cid = await signup('Cid Rocha');
  const s8 = await deal(cid);
  await done(s8.order);
  await age(s8.order, '25 hours');
  await followups();
  ok((await get(s8.order)).confirm_reminders === 1, 'lembrete com 1 dia');
  const pushes = (await db.query('select count(*)::int n from private.push_sends')).rows[0].n;
  await followups();
  ok((await get(s8.order)).confirm_reminders === 1, 'não repete antes de 3 dias');
  const conv8 = s8.conv;
  ok(!(await as(cid, "select public.create_request($1, 'encanador', 'Outro', 'Hoje')", [conv8])).error, 'com 1 dia ainda faz pedido novo');
  await age(s8.order, '73 hours');
  await followups();
  ok((await get(s8.order)).confirm_reminders === 2, 'lembrete com 3 dias');
  ok((await as(cid, "select public.create_request($1, 'encanador', 'Mais um', 'Hoje')", [conv8])).error?.includes('Confirme o serviço com Marcos'), 'com 3 dias sem responder: não faz pedido novo');
  ok((await as(pro, 'select public.ask_team_order($1)', [s8.order])).error?.includes('7 dias'), 'ajuda da equipe só com 7 dias');
  await age(s8.order, '8 days');
  await followups();
  ok((await get(s8.order)).status === 'combinado', 'sem foto: nunca conclui sozinho');
  ok(!(await as(pro, 'select public.ask_team_order($1)', [s8.order])).error, 'profissional pede ajuda à equipe');
  const help = (await db.query("select * from public.reports where order_id = $1 and reason = 'servico'", [s8.order])).rows[0];
  ok(!!help && help.reporter_id === pro && help.reported_id === cid, 'vira denúncia de serviço no painel');
  ok((await as(pro, 'select public.ask_team_order($1)', [s8.order])).error?.includes('já está analisando'), 'uma vez só');
  ok((await adm('select public.admin_resolve_service($1, true)', [help.id])).error === undefined, 'equipe decide: foi feito');
  const c8 = await get(s8.order);
  ok(c8.status === 'concluido' && c8.completed_by === 'equipe' && !c8.client_contest_wrong, 'concluído pela equipe (sumir não é contestação indevida)');
  ok(!(await as(cid, "select public.create_request($1, 'encanador', 'Agora sim', 'Hoje')", [conv8])).error, 'cliente volta a fazer pedidos');

  console.log('\nCom foto: conclui sozinho em 7 dias');
  const dani = await signup('Dani Alves');
  const s9 = await deal(dani);
  await done(s9.order, [`${s9.order}/1.jpg`]);
  ok((await lastNote(s9.conv)) === 'Serviço marcado como feito (com fotos). Dani, confirme se foi feito.', 'aviso menciona as fotos');
  await age(s9.order, '6 days');
  await followups();
  ok((await get(s9.order)).status === 'combinado', 'com 6 dias: ainda aguardando');
  ok((await as(pro, 'select public.ask_team_order($1)', [s9.order])).error !== undefined, 'com foto não precisa pedir ajuda');
  await age(s9.order, '7 days 1 hour');
  const j9 = await jobs();
  await followups();
  const c9 = await get(s9.order);
  ok(c9.status === 'concluido' && c9.completed_by === 'automatico' && (await jobs()) === j9 + 1, 'com 7 dias: concluído automaticamente');
  ok((await lastNote(s9.conv)) === 'Serviço concluído automaticamente: Dani não respondeu em 7 dias.', 'aviso no chat');

  console.log('\nDiscordar');
  const eva = await signup('Eva Dias');
  const s10 = await deal(eva);
  ok((await as(pro, 'select public.dispute_order($1)', [s10.order])).error?.includes('depois que o cliente disser'), 'só discorda depois de um "não"');
  await done(s10.order, [`${s10.order}/1.jpg`]);
  await confirm(eva, s10.order, false);
  ok((await get(s10.order)).done_photos.length === 1, 'as fotos ficam guardadas depois do "não" (prova para a equipe)');
  ok(!(await as(pro, 'select public.dispute_order($1)', [s10.order])).error, 'profissional discorda');
  ok((await lastNote(s10.conv)) === 'O profissional discordou. A equipe da Rezolveaê vai analisar a conversa e decidir.', 'aviso no chat');
  ok(!!(await get(s10.order)).disputed_at, 'serviço aparece como em análise (disputed_at)');
  ok((await as(eva, 'select public.cancel_order($1)', [s10.order])).error?.includes('equipe da Rezolveaê está analisando'), 'em disputa: ninguém cancela');
  ok((await as(eva, "select public.request_reschedule($1, now() + interval '1 day', 'Amanhã')", [s10.order])).error?.includes('equipe da Rezolveaê está analisando'), 'em disputa: ninguém remarca');
  const disp = (await db.query("select id from public.reports where order_id = $1", [s10.order])).rows[0].id;
  const rep = (await adm('select public.admin_report($1) r', [disp])).rows[0].r;
  ok(rep.order?.service === 'Encanador' && rep.reason === 'servico', 'a denúncia mostra o serviço em disputa');
  ok(!!(await as(pro, 'select public.admin_resolve_service($1, true)', [disp])).error, 'só a equipe decide');
  await adm('select public.admin_resolve_service($1, true)', [disp]);
  const c10 = await get(s10.order);
  ok(c10.status === 'concluido' && c10.completed_by === 'equipe' && c10.client_contest_wrong, 'equipe: foi feito → concluído e contestação indevida marcada');
  ok(!c10.disputed_at, 'decidido: sai de análise');
  const conv10 = s10.conv;
  ok((await one(pro, 'select * from public.client_track_record($1)', [eva])).wrong_contests === 1, 'aparece no histórico do cliente para o profissional');
  ok((await lastNote(conv10)) === 'A equipe da Rezolveaê confirmou que o serviço foi feito. Serviço concluído.', 'aviso no chat');

  const s11 = await deal(eva);
  await done(s11.order); await confirm(eva, s11.order, false); await as(pro, 'select public.dispute_order($1)', [s11.order]);
  const disp2 = (await db.query("select id from public.reports where order_id = $1", [s11.order])).rows[0].id;
  await adm('select public.admin_resolve_service($1, false)', [disp2]);
  const c11 = await get(s11.order);
  ok(c11.status === 'combinado' && c11.done_blocked && !c11.client_contest_wrong, 'equipe: não foi feito → segue combinado, para remarcar ou cancelar');

  console.log('\nDia seguinte sem "feito"');
  const fe = await signup('Fê Costa');
  const s12 = await deal(fe, -30);
  await db.query("update public.orders set scheduled_at = now() - interval '2 days' where id = $1", [s12.order]);
  await followups();
  ok(!!(await get(s12.order)).followup_at, 'o profissional recebe "O serviço aconteceu?"');
  const f1 = (await get(s12.order)).followup_at;
  await followups();
  ok(+(await get(s12.order)).followup_at === +f1, 'uma vez só por data');

  console.log('\nFotos');
  const pol = (await db.query("select policyname from pg_policies where tablename = 'objects' and policyname like 'done-photos:%' order by 1")).rows.map((r) => r.policyname);
  ok(pol.length === 4, `bucket privado com políticas: ${pol.join(', ')}`);

  console.log(`\n${pass} ok, ${fail} falhas`);
  await db.end();
  process.exit(fail ? 1 : 0);
})().catch((e) => { console.error('ERRO', e); process.exit(1); });
